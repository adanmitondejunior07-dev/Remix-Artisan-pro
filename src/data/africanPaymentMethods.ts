export function findCountryByCode(code: string): AfricanPaymentCountry {
  return (
    AFRICAN_PAYMENT_COUNTRIES.find((c) => c.code.toUpperCase() === code.toUpperCase()) ||
    AFRICAN_PAYMENT_COUNTRIES[0]
  );
}

export function formatLocalPrice(fcfaAmount: number, country: AfricanPaymentCountry): { formatted: string; raw: number } {
  if (country.currency === 'FCFA') {
    return {
      formatted: `${fcfaAmount.toLocaleString('fr-FR')} FCFA`,
      raw: fcfaAmount,
    };
  }

  // Convert based on exchange rate
  const localVal = Math.round(fcfaAmount / country.currencyToFcfaRate);
  return {
    formatted: `${localVal.toLocaleString('fr-FR')} ${country.currencySymbol}`,
    raw: localVal,
  };
}
